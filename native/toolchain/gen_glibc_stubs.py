"""Link-only stubs of glibc 2.27 (the head unit's), from glibc's own ABI lists.

The head unit (MGU, iDrive 7) runs glibc 2.27. A program linked against a newer
glibc asks for symbol versions the unit does not have and will not start there.
This writes, for each glibc library, an assembly file that defines every symbol
of abilists/<lib>.abilist (glibc-2.27, sysdeps/unix/sysv/linux/x86_64/64) and a
version script that gives each its newest 2.27 version; gcc turns the two into
a shared library with the real SONAME. Linking against these, the program can
only bind what glibc 2.27 has, with the versions it has.

  gen_glibc_stubs.py <abilists dir> <out dir>
"""
import os
import re
import sys

LIBS = {  # abilist name -> SONAME
    'libc': 'libc.so.6', 'libpthread': 'libpthread.so.0', 'libm': 'libm.so.6',
    'libdl': 'libdl.so.2', 'librt': 'librt.so.1', 'ld': 'ld-linux-x86-64.so.2',
}


def vkey(v):
    return [int(x) for x in re.sub(r'^GLIBC_', '', v).split('.')]


def main(src, out):
    os.makedirs(out, exist_ok=True)
    for lib, soname in LIBS.items():
        syms = {}      # name -> (version, kind, size)
        nodes = set()
        for line in open(os.path.join(src, lib + '.abilist')):
            p = line.split()
            if len(p) < 3 or not p[0].startswith('GLIBC_2'):
                continue          # GLIBC_PRIVATE and the like: not for programs
            ver, name, kind = p[0], p[1], p[2]
            if kind == 'A':
                nodes.add(ver)
                continue
            size = int(p[3], 16) if len(p) > 3 else 0
            if name not in syms or vkey(ver) > vkey(syms[name][0]):
                syms[name] = (ver, kind, size)
            nodes.add(ver)
        asm = ['/* generated by gen_glibc_stubs.py from glibc 2.27 %s.abilist */' % lib, '.text']
        for name, (ver, kind, size) in sorted(syms.items()):
            if kind == 'F':
                asm += ['.globl %s' % name, '.type %s,@function' % name, '%s: ret' % name]
        asm.append('.data')
        for name, (ver, kind, size) in sorted(syms.items()):
            if kind == 'D':
                asm += ['.globl %s' % name, '.type %s,@object' % name, '.size %s,%d' % (name, max(size, 1)),
                        '.balign 16', '%s: .zero %d' % (name, max(size, 1))]
        asm.append('.section .note.GNU-stack,"",@progbits')
        open(os.path.join(out, lib + '.S'), 'w').write('\n'.join(asm) + '\n')
        vs, prev = [], None
        for node in sorted(nodes, key=vkey):
            names = sorted(n for n, s in syms.items() if s[0] == node)
            body = ('  global:\n' + ''.join('    %s;\n' % n for n in names)) if names else ''
            vs.append('%s {\n%s}%s;\n' % (node, body, (' ' + prev) if prev else ''))
            prev = node
        open(os.path.join(out, lib + '.map'), 'w').write(''.join(vs))
        open(os.path.join(out, lib + '.soname'), 'w').write(soname + '\n')
        print('%s: %d symbols, %d versions -> %s' % (lib, len(syms), len(nodes), soname))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
